"""Client-readable PDF for a completed single-agent synthetic assessment."""
import io
from xml.sax.saxutils import escape
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT, TA_CENTER
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, PageBreak
from . import __version__

NAVY=colors.HexColor("#0B1A27")
INK=colors.HexColor("#1B2D3A")
MUTED=colors.HexColor("#5C7181")
TEAL=colors.HexColor("#0F8F85")
LIGHT=colors.HexColor("#EFF7F6")


def render_product_report(data):
    a=data['assessment']; run=data['run']; risk=run['risk_profile']
    bio=io.BytesIO()
    pdf=SimpleDocTemplate(bio,pagesize=(612,792),rightMargin=46,leftMargin=46,topMargin=50,bottomMargin=47,
                           title='SIYAJ | Agent Assurance Report',author='SIYAJ Assurance Platform')
    styles=getSampleStyleSheet()
    styles.add(ParagraphStyle(name='HeroArg',parent=styles['Title'],fontName='Helvetica-Bold',fontSize=25,leading=30,textColor=NAVY,spaceAfter=10,alignment=TA_LEFT))
    styles.add(ParagraphStyle(name='HeadArg',fontName='Helvetica-Bold',fontSize=12,leading=15,textColor=NAVY,spaceBefore=17,spaceAfter=8))
    styles.add(ParagraphStyle(name='BodyArg',fontName='Helvetica',fontSize=9,leading=14,textColor=INK,spaceAfter=5))
    styles.add(ParagraphStyle(name='SmallArg',fontName='Helvetica',fontSize=8,leading=11,textColor=MUTED,spaceAfter=5))
    styles.add(ParagraphStyle(name='TableArg',fontName='Helvetica',fontSize=8,leading=12,textColor=INK))
    styles.add(ParagraphStyle(name='TableHeadingArg',fontName='Helvetica-Bold',fontSize=8,leading=12,textColor=colors.white))
    P=lambda x,sty='BodyArg':Paragraph(escape(str(x)).replace('\n','<br/>'),styles[sty])
    story=[P('SIYAJ  /  ASSURANCE LAB','SmallArg'),Spacer(1,12),P('Agent assurance report','HeroArg'),
           P('Observed behavior under synthetic adversarial testing','BodyArg'),Spacer(1,12)]
    metadata=[('Engagement',a['project_name']),('Client',a['client_name']),('Jurisdiction',a['region']),
              ('Agent',a['agent_name']),('Evaluation mode',a['agent_mode']),('Dataset',a['dataset_name']),
              ('Report reference',a['id']),('Assessment status',run['status'].upper()),
              ('Generated by', f'SIYAJ assurance workspace {__version__}')]
    box=Table([[P(k,'SmallArg'),P(v)] for k,v in metadata],colWidths=[132,382],hAlign='LEFT')
    box.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,-1),LIGHT),('TOPPADDING',(0,0),(-1,-1),7),('BOTTOMPADDING',(0,0),(-1,-1),7),
              ('LEFTPADDING',(0,0),(-1,-1),10),('LINEBELOW',(0,0),(-1,-2),.3,colors.HexColor('#DAE6E6'))]))
    story.extend([box,Spacer(1,20)])
    val=risk.get('observed_exposure_index'); cover=risk.get('coverage_pct')
    tiles=[['OBSERVED EXPOSURE','EVIDENCE COVERAGE','OBSERVED FAILURES'],
           [str(val)+'/100' if val is not None else 'NOT SCORED',str(cover)+'%' if cover is not None else 'NOT SCORED',str(risk.get('observed_failures',0))]]
    k=Table([[P(v,'SmallArg') if j==0 else P(v,'HeadArg') for v in row] for j,row in enumerate(tiles)],colWidths=[171]*3)
    k.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,-1),LIGHT),('VALIGN',(0,0),(-1,-1),'MIDDLE'),
                           ('TOPPADDING',(0,0),(-1,-1),10),('BOTTOMPADDING',(0,0),(-1,-1),10),
                           ('LINEBEFORE',(1,0),(-1,-1),1,colors.white)]))
    story.extend([k,Spacer(1,10),P('Risk tier: '+str(risk.get('risk_tier','NOT ASSESSED'))+' | Evidence strength: '+str(risk.get('evidence_strength','unknown')),'SmallArg')])
    story.append(P('Executive interpretation','HeadArg'))
    story.append(P('Results reflect a bounded selection of synthetic tests, evaluated against the observed agent responses and tool-attempt traces. PASS indicates the test did not identify its particular violation. REVIEW or ERROR does not demonstrate safety.'))
    story.append(P('Assessment authorization','HeadArg'))
    story.append(P('Authorized by: '+a['authorized_by']))
    story.append(P(a['scope_note']))
    story.append(P('Dataset SHA-256: '+a['dataset_fingerprint'],'SmallArg'))
    story.append(P('Findings by security dimension','HeadArg'))
    dims=risk.get('dimensions',[])
    if dims:
        rows=[[P('Dimension','TableHeadingArg'),P('Failures','TableHeadingArg'),P('Coverage','TableHeadingArg'),P('Recommendation','TableHeadingArg')]]
        for dim in dims:
            rows.append([P(dim['name'],'TableArg'),P(dim.get('failed',0),'TableArg'),
                         P(str(dim.get('scored',0))+'/'+str(dim.get('tested',0)),'TableArg'),P(dim['mitigation'],'TableArg')])
        t=Table(rows,colWidths=[111,48,60,295],repeatRows=1,hAlign='LEFT')
        t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),NAVY),('VALIGN',(0,0),(-1,-1),'TOP'),
           ('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white,LIGHT]),('BOTTOMPADDING',(0,0),(-1,-1),8),
           ('TOPPADDING',(0,0),(-1,-1),8),('LINEBELOW',(0,0),(-1,0),.4,TEAL)]))
        story.append(t)
    story.append(P('Evidence and analyst review','HeadArg'))
    findings=[r for r in run.get('results',[]) if r['status'] in ('fail','review','error')]
    if not findings:
        story.append(P('No failed, unresolved or error cases in this bounded run. This does not establish general agent safety.'))
    else:
        for f in findings[:35]:
            sub=[P(f"{f['case_id']}  |  {f['severity']}  |  {f['status'].upper()}  -  {f['title']}",'HeadArg'),
                 P('Evaluator: '+f['reason'],'BodyArg')]
            tr=f.get('analyst_review')
            if tr:
                sub.append(P('Analyst: '+tr['disposition'].replace('_',' ')+' - '+tr['note'],'BodyArg'))
            else:
                sub.append(P('Analyst disposition: Not yet reviewed','SmallArg'))
            story.append(KeepTogether(sub))
    story.extend([P('Scope and limitations','HeadArg'),
         P('This report is not an insurance underwriting score, regulatory certification, full penetration test, or prediction of breach likelihood. Indicators are heuristic and based on sampled cases only. A scripted demo agent is demonstration evidence, not live model evaluation.'),
         P('This local-first software does not isolate arbitrary code, verify data residency, operate privileged real-world tools, or provide a production multi-tenant trust boundary. Remote agent isolation and authorization are the owner\'s responsibility.'),
         P('Control alignment reference: OWASP Top 10 for Agentic Applications (2026), https://genai.owasp.org/resource/owasp-top-10-for-agentic-applications-for-2026/','SmallArg')])
    def footer(c,doc):
        c.setStrokeColor(colors.HexColor('#DFE8E8'));c.line(46,40,566,40)
        c.setFont('Helvetica',7);c.setFillColor(MUTED)
        c.drawString(46,28,'SIYAJ  |  SYNTHETIC AGENT ASSURANCE EVIDENCE')
        c.drawRightString(565,28,'Page '+str(doc.page))
    pdf.build(story,onFirstPage=footer,onLaterPages=footer)
    return bio.getvalue()
